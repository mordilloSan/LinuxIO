import { describe, expect, it } from "vitest";

import { isReadOnlyCommand } from "./readOnlyCommand";

describe("isReadOnlyCommand", () => {
  it.each([
    "ls -la /etc",
    "systemctl status nginx",
    "sudo systemctl --no-pager status nginx",
    "journalctl -u nginx -b | tail -n 50",
    "ss -ltnp 'sport = :80'",
    "cat /etc/os-release 2>/dev/null",
    "df -h && free -m",
    "docker compose ps",
    "btrfs filesystem usage /",
    "ip addr show",
    "LANG=C date",
    "find /var -name '*.log'",
    "timedatectl",
    "rg -n --no-heading -i '^\\s*(PubkeyAuthentication|PasswordAuthentication)' /etc/ssh",
    'grep -E "a|b; c > d" /etc/hosts',
    "echo 'a > b' | wc -c",
    "env",
    "env LANG=C ls -la",
    "env -i PATH=/usr/bin ls",
    "env -S 'ls -la' /etc",
    `echo "it's" | wc -c`,
    "date -u",
    "date -d '2 days ago' +%F",
    "hostname -f",
    "sort -k2 -t: /etc/passwd",
    "uniq -c /tmp/list",
    "ls /nope 2>&1 | head",
    "ls &>/dev/null",
    "ls \\\n  -la",
  ])("treats %s as reading", (command) => {
    expect(isReadOnlyCommand(command)).toBe(true);
  });

  it.each([
    "systemctl restart nginx",
    "systemctl disable --now apache2",
    "rm -rf /tmp/x",
    "echo hi > /etc/motd",
    "cat $(which nginx)",
    "ls; reboot",
    "sed -i s/a/b/ /etc/hosts",
    "find /var -name '*.log' -delete",
    "journalctl --vacuum-time=2d",
    "ip link set eth0 down",
    "docker rm web",
    "apt upgrade",
    "git checkout main",
    "timedatectl set-timezone UTC",
    'echo "$(reboot)"',
    "echo 'x' > /etc/motd",
    "find / '-delete'",
    "env rm -rf /tmp/x",
    "env -S 'rm -rf /tmp/x'",
    "env --split-string='rm x'",
    "env -u HOME rm x",
    "env -S 'ls; rm x'",
    `echo "it's"; rm -rf /tmp/x; echo 'a'`,
    "echo 'unclosed",
    "ls 2>/tmp/err",
    "sort -o /etc/passwd /tmp/x",
    "sort --compress-program=sh /tmp/x",
    "uniq /tmp/a /etc/hosts",
    "date -s 2020-01-01",
    "date 010100002020",
    "hostname evil",
    "hostname -F /tmp/name",
    "tree -o /etc/motd",
    "rg --pre sh x",
    "ss -K dst 192.0.2.1",
    "git diff --output=/etc/motd",
    "__proto__ x",
    "constructor x",
  ])("treats %s as acting", (command) => {
    expect(isReadOnlyCommand(command)).toBe(false);
  });
});
